#!/usr/bin/env python3
"""fetch_weather.py — pull current weather for major world cities into weather.js.

Keyless source: Open-Meteo (https://open-meteo.com) — free, no API key, no CORS
restriction concerns because this runs server-side and writes `weather.js`
(window.WEATHER) that the dashboard reads same-origin.

The city list mirrors the dashboard's own World Clock (ZONES in app.js), so the
weather report and the clocks/map pins stay consistent. One Open-Meteo request
per city (15 requests/hour is trivial).

Usage:
    python3 fetch_weather.py            # write weather.js in place (if changed)
    python3 fetch_weather.py --commit   # write + commit + push (only when changed)
"""
import datetime, json, os, subprocess, sys, urllib.request

HOME = os.path.expanduser('~')
REPO = os.environ.get('WM_REPO_DIR') or os.path.join(HOME, 'world-monitor')
OUT = os.path.join(REPO, 'weather.js')
UA = {'User-Agent': 'WorldMonitor-WeatherFetcher/1.0 (public Open-Meteo open data)'}

# Same cities as the dashboard World Clock (ZONES), minus the UTC/Greenwich pseudo-entry.
CITIES = [
    ('Los Angeles', 34.0537, -118.2428),
    ('New York',    40.7127,  -74.0060),
    ('Toronto',     43.6535,  -79.3839),
    ('Sao Paulo',  -23.5507,  -46.6334),
    ('London',      51.5074,   -0.1278),
    ('Frankfurt',   50.1106,    8.6821),
    ('Moscow',      55.6256,   37.6064),
    ('Istanbul',    41.0064,   28.9759),
    ('Dubai',       25.0743,   55.1886),
    ('New Delhi',   28.6139,   77.2090),
    ('Singapore',    1.3571,  103.8195),
    ('Beijing',     39.9057,  116.3913),
    ('Tokyo',       35.6769,  139.7639),
    ('Sydney',     -33.8698,  151.2083),
    ('Auckland',   -36.8521,  174.7632),
]

# WMO weather interpretation codes -> (condition, emoji)
WMO = {
    0: ('clear sky', '☀️'), 1: ('mainly clear', '🌤️'), 2: ('partly cloudy', '⛅'),
    3: ('overcast', '☁️'), 45: ('fog', '🌫️'), 48: ('rime fog', '🌫️'),
    51: ('light drizzle', '🌦️'), 53: ('drizzle', '🌦️'), 55: ('dense drizzle', '🌦️'),
    56: ('freezing drizzle', '🌧️'), 57: ('freezing drizzle', '🌧️'),
    61: ('light rain', '🌧️'), 63: ('rain', '🌧️'), 65: ('heavy rain', '🌧️'),
    66: ('freezing rain', '🌧️'), 67: ('freezing rain', '🌧️'),
    71: ('light snow', '🌨️'), 73: ('snow', '🌨️'), 75: ('heavy snow', '❄️'),
    77: ('snow grains', '🌨️'), 80: ('rain showers', '🌦️'), 81: ('rain showers', '🌦️'),
    82: ('violent rain', '🌧️'), 85: ('snow showers', '🌨️'), 86: ('snow showers', '🌨️'),
    95: ('thunderstorm', '⛈️'), 96: ('thunderstorm w/ hail', '⛈️'), 99: ('thunderstorm w/ hail', '⛈️'),
}


def wmo(code):
    code = int(code or 0)
    return WMO.get(code, ('—', '🌡️'))


def fetch_city(city, lat, lng):
    url = ('https://api.open-meteo.com/v1/forecast?latitude=%f&longitude=%f'
           '&current=temperature_2m,apparent_temperature,relative_humidity_2m,'
           'weather_code,wind_speed_10m,is_day'
           '&daily=temperature_2m_max,temperature_2m_min,weather_code'
           '&timezone=auto&forecast_days=1' % (lat, lng))
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=20) as r:
        d = json.loads(r.read().decode('utf-8', 'ignore'))
    c = d.get('current') or {}
    daily = d.get('daily') or {}
    cond, emoji = wmo(c.get('weather_code'))
    tmax = (daily.get('temperature_2m_max') or [None])[0]
    tmin = (daily.get('temperature_2m_min') or [None])[0]
    return {
        'city': city,
        'lat': round(float(lat), 4),
        'lng': round(float(lng), 4),
        'tempC': c.get('temperature_2m'),
        'feelsC': c.get('apparent_temperature'),
        'humidity': c.get('relative_humidity_2m'),
        'windKmh': c.get('wind_speed_10m'),
        'code': c.get('weather_code'),
        'cond': cond,
        'emoji': emoji,
        'isDay': c.get('is_day'),
        'tMax': tmax,
        'tMin': tmin,
        'local': (c.get('time') or '')[:16],
        'tz': d.get('timezone'),
    }


def main():
    cities, ok = [], 0
    for city, lat, lng in CITIES:
        try:
            cities.append(fetch_city(city, lat, lng))
            ok += 1
        except Exception as e:
            print('weather fetch failed (%s): %s' % (city, e))
    if not cities:
        print('parsed 0 cities from Open-Meteo — aborting to avoid clobbering')
        sys.exit(1)

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    data = {
        '_updated': stamp,
        'source': 'Open-Meteo',
        'sources': '%d/%d cities' % (ok, len(CITIES)),
        'count': len(cities),
        'cities': cities,
    }
    content = ('// AUTO-GENERATED by fetch_weather.py — do not edit by hand.\n'
               '// Current weather for major world cities via Open-Meteo (keyless).\n'
               'window.WEATHER = ' + json.dumps(data, ensure_ascii=False) + ';\n')

    def sig(d):
        return json.dumps([(c['city'], c['tempC'], c['code'], c['tMax'], c['tMin'])
                           for c in d.get('cities', [])], sort_keys=True)
    prev = {}
    if os.path.exists(OUT):
        try:
            prev = json.loads(open(OUT, encoding='utf-8').read().split('=', 1)[1].rsplit(';', 1)[0])
        except Exception:
            prev = {}
    if sig(data) == sig(prev):
        print('weather.js unchanged (%d cities, %s)' % (len(cities), stamp))
        return 0
    open(OUT, 'w', encoding='utf-8').write(content)
    print('wrote weather.js: %d/%d cities, %s' % (len(cities), len(CITIES), stamp))
    if '--commit' in sys.argv:
        subprocess.run(['git', '-C', REPO, 'add', 'weather.js'], check=True)
        subprocess.run(['git', '-C', REPO, 'commit', '-m',
                        'weather: Open-Meteo snapshot (%s)' % stamp[:16]], check=True)
        subprocess.run(['git', '-C', REPO, 'push', 'origin', 'main'], check=True)
        print('committed + pushed')
    return 0


if __name__ == '__main__':
    sys.exit(main())
